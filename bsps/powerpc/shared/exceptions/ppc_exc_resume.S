#include <rtems/asm.h>
#include <rtems/score/cpuimpl.h>

#define SCRATCH_REGISTER r4

	.globl _CPU_Exception_resume

	.text
	.type _CPU_Exception_resume, @function

_CPU_Exception_resume:

	.cfi_startproc
	subi	r3, r3, FRAME_LINK_SPACE

	/* Enable AltiVec, FPU, and SPE */
#if defined(PPC_MULTILIB_ALTIVEC) || defined(PPC_MULTILIB_FPU) || defined(__SPE__)
	mfmsr	SCRATCH_REGISTER
#ifdef PPC_MULTILIB_ALTIVEC
	oris	SCRATCH_REGISTER, SCRATCH_REGISTER, MSR_VE >> 16
#endif
#ifdef PPC_MULTILIB_FPU
	ori	SCRATCH_REGISTER, SCRATCH_REGISTER, MSR_FP
#endif
#ifdef __SPE__
	oris	SCRATCH_REGISTER, SCRATCH_REGISTER, MSR_SPE >> 16
#endif
	mtmsr	SCRATCH_REGISTER
	isync
#endif

#ifdef PPC_MULTILIB_FPU
	/* Restore volatile FPU context */
	lfd	f0, PPC_EXC_FPSCR_OFFSET(r3)
	mtfsf	0xff, f0
	lfd	f0, PPC_EXC_FR_OFFSET(0)(r3)
	lfd	f1, PPC_EXC_FR_OFFSET(1)(r3)
	lfd	f2, PPC_EXC_FR_OFFSET(2)(r3)
	lfd	f3, PPC_EXC_FR_OFFSET(3)(r3)
	lfd	f4, PPC_EXC_FR_OFFSET(4)(r3)
	lfd	f5, PPC_EXC_FR_OFFSET(5)(r3)
	lfd	f6, PPC_EXC_FR_OFFSET(6)(r3)
	lfd	f7, PPC_EXC_FR_OFFSET(7)(r3)
	lfd	f8, PPC_EXC_FR_OFFSET(8)(r3)
	lfd	f9, PPC_EXC_FR_OFFSET(9)(r3)
	lfd	f10, PPC_EXC_FR_OFFSET(10)(r3)
	lfd	f11, PPC_EXC_FR_OFFSET(11)(r3)
	lfd	f12, PPC_EXC_FR_OFFSET(12)(r3)
	lfd	f13, PPC_EXC_FR_OFFSET(13)(r3)
	lfd	f14, PPC_EXC_FR_OFFSET(14)(r3)
	lfd	f15, PPC_EXC_FR_OFFSET(15)(r3)
	lfd	f16, PPC_EXC_FR_OFFSET(16)(r3)
	lfd	f17, PPC_EXC_FR_OFFSET(17)(r3)
	lfd	f18, PPC_EXC_FR_OFFSET(18)(r3)
	lfd	f19, PPC_EXC_FR_OFFSET(19)(r3)
	lfd	f20, PPC_EXC_FR_OFFSET(20)(r3)
	lfd	f21, PPC_EXC_FR_OFFSET(21)(r3)
	lfd	f22, PPC_EXC_FR_OFFSET(22)(r3)
	lfd	f23, PPC_EXC_FR_OFFSET(23)(r3)
	lfd	f24, PPC_EXC_FR_OFFSET(24)(r3)
	lfd	f25, PPC_EXC_FR_OFFSET(25)(r3)
	lfd	f26, PPC_EXC_FR_OFFSET(26)(r3)
	lfd	f27, PPC_EXC_FR_OFFSET(27)(r3)
	lfd	f28, PPC_EXC_FR_OFFSET(28)(r3)
	lfd	f29, PPC_EXC_FR_OFFSET(29)(r3)
	lfd	f30, PPC_EXC_FR_OFFSET(30)(r3)
	lfd	f31, PPC_EXC_FR_OFFSET(31)(r3)
#endif

#ifdef PPC_MULTILIB_ALTIVEC
	/* Restore AltiVec context */
	li	SCRATCH_REGISTER, PPC_EXC_VSCR_OFFSET
	lvewx	v0, r3, SCRATCH_REGISTER
	mtvscr	v0
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(0)
	lvx	v0, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(1)
	lvx	v1, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(2)
	lvx	v2, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(3)
	lvx	v3, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(4)
	lvx	v4, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(5)
	lvx	v5, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(6)
	lvx	v6, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(7)
	lvx	v7, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(8)
	lvx	v8, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(9)
	lvx	v9, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(10)
	lvx	v10, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(11)
	lvx	v11, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(12)
	lvx	v12, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(13)
	lvx	v13, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(14)
	lvx	v14, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(15)
	lvx	v15, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(16)
	lvx	v16, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(17)
	lvx	v17, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(18)
	lvx	v18, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(19)
	lvx	v19, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(20)
	lvx	v20, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(21)
	lvx	v21, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(22)
	lvx	v22, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(23)
	lvx	v23, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(24)
	lvx	v24, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(25)
	lvx	v25, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(26)
	lvx	v26, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(27)
	lvx	v27, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(28)
	lvx	v28, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(29)
	lvx	v29, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(30)
	lvx	v30, r3, SCRATCH_REGISTER
	li	SCRATCH_REGISTER, PPC_EXC_VR_OFFSET(31)
	lvx	v31, r3, SCRATCH_REGISTER
	lwz	SCRATCH_REGISTER, PPC_EXC_VRSAVE_OFFSET(r3)
	mtvrsave	SCRATCH_REGISTER
#endif

#ifdef __SPE__
	/* Restore SPEFSCR and ACC */
	lwz	SCRATCH_REGISTER, PPC_EXC_SPEFSCR_OFFSET(r3)
	mtspr	FSL_EIS_SPEFSCR, SCRATCH_REGISTER
	evldd	SCRATCH_REGISTER, PPC_EXC_ACC_OFFSET(r3)
	evmra	SCRATCH_REGISTER, SCRATCH_REGISTER
#endif

	/* Restore special registers */
	lwz	SCRATCH_REGISTER, EXC_XER_OFFSET(r3)
	mtxer	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, EXC_CTR_OFFSET(r3)
	mtctr	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, EXC_LR_OFFSET(r3)
	mtlr	SCRATCH_REGISTER

	/* Restore general purpose registers */
	PPC_GPR_LOAD	r0, GPR0_OFFSET(r3)
	PPC_GPR_LOAD	r1, GPR1_OFFSET(r3)
	PPC_GPR_LOAD	r2, GPR2_OFFSET(r3)
	/* r3 is restored later */
	/* SCRATCH_REGISTER is restored later */
	PPC_GPR_LOAD	r5, GPR5_OFFSET(r3)
	PPC_GPR_LOAD	r6, GPR6_OFFSET(r3)
	PPC_GPR_LOAD	r7, GPR7_OFFSET(r3)
	PPC_GPR_LOAD	r8, GPR8_OFFSET(r3)
	PPC_GPR_LOAD	r9, GPR9_OFFSET(r3)
	PPC_GPR_LOAD	r10, GPR10_OFFSET(r3)
	PPC_GPR_LOAD	r11, GPR11_OFFSET(r3)
	PPC_GPR_LOAD	r12, GPR12_OFFSET(r3)
	PPC_GPR_LOAD	r13, GPR13_OFFSET(r3)
	PPC_GPR_LOAD	r14, GPR14_OFFSET(r3)
	PPC_GPR_LOAD	r15, GPR15_OFFSET(r3)
	PPC_GPR_LOAD	r16, GPR16_OFFSET(r3)
	PPC_GPR_LOAD	r17, GPR17_OFFSET(r3)
	PPC_GPR_LOAD	r18, GPR18_OFFSET(r3)
	PPC_GPR_LOAD	r19, GPR19_OFFSET(r3)
	PPC_GPR_LOAD	r20, GPR20_OFFSET(r3)
	PPC_GPR_LOAD	r21, GPR21_OFFSET(r3)
	PPC_GPR_LOAD	r22, GPR22_OFFSET(r3)
	PPC_GPR_LOAD	r23, GPR23_OFFSET(r3)
	PPC_GPR_LOAD	r24, GPR24_OFFSET(r3)

	/* Reduce offset due to SPE instruction limitations */
	addi	SCRATCH_REGISTER, r3, GPR24_OFFSET
	PPC_GPR_LOAD	r25, (GPR25_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)
	PPC_GPR_LOAD	r26, (GPR26_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)
	PPC_GPR_LOAD	r27, (GPR27_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)
	PPC_GPR_LOAD	r28, (GPR28_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)
	PPC_GPR_LOAD	r29, (GPR29_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)
	PPC_GPR_LOAD	r30, (GPR30_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)
	PPC_GPR_LOAD	r31, (GPR31_OFFSET - GPR24_OFFSET)(SCRATCH_REGISTER)

	lwz	SCRATCH_REGISTER, EXC_TYPE_OFFSET(r3)
	cmpwi	SCRATCH_REGISTER, 1
	beq	.Lrfci
	cmpwi	SCRATCH_REGISTER, 2
	beq	.Lrfmci

	lwz	SCRATCH_REGISTER, EXC_CR_OFFSET(r3)
	mtcr	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, SRR0_FRAME_OFFSET(r3)
	mtsrr0	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, SRR1_FRAME_OFFSET(r3)
	mtsrr1	SCRATCH_REGISTER
	PPC_GPR_LOAD	SCRATCH_REGISTER, GPR4_OFFSET(r3)
	PPC_GPR_LOAD	r3, GPR3_OFFSET(r3)

	rfi

.Lrfci:

	lwz	SCRATCH_REGISTER, EXC_CR_OFFSET(r3)
	mtcr	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, SRR0_FRAME_OFFSET(r3)
	mtcsrr0	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, SRR1_FRAME_OFFSET(r3)
	mtcsrr1	SCRATCH_REGISTER
	PPC_GPR_LOAD	SCRATCH_REGISTER, GPR4_OFFSET(r3)
	PPC_GPR_LOAD	r3, GPR3_OFFSET(r3)

	rfci

.Lrfmci:

	lwz	SCRATCH_REGISTER, EXC_CR_OFFSET(r3)
	mtcr	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, SRR0_FRAME_OFFSET(r3)
	mtmcsrr0	SCRATCH_REGISTER
	PPC_REG_LOAD	SCRATCH_REGISTER, SRR1_FRAME_OFFSET(r3)
	mtmcsrr1	SCRATCH_REGISTER
	PPC_GPR_LOAD	SCRATCH_REGISTER, GPR4_OFFSET(r3)
	PPC_GPR_LOAD	r3, GPR3_OFFSET(r3)

	rfmci

	.cfi_endproc
	.size	_CPU_Exception_resume, . - _CPU_Exception_resume
